function isPlainObject(value: unknown): value is Record<string, unknown> {
  if (typeof value !== 'object' || value === null) return false;
  const proto: unknown = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
}

function cloneDeep<T>(value: T): T {
  if (Array.isArray(value)) return value.map(cloneDeep) as T;
  if (isPlainObject(value)) {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(value)) out[key] = cloneDeep((value as Record<string, unknown>)[key]);
    return out as T;
  }
  return value;
}

/**
 * Deep-merges `override` over `base`. Plain objects merge recursively;
 * arrays, functions, class instances, and scalars replace. `undefined`
 * values in the override are ignored. Results never alias mutable state
 * (arrays/objects) of either operand.
 */
export function mergeDeep<T>(base: T, override: unknown): T {
  if (override === undefined) return cloneDeep(base);
  if (!isPlainObject(base) || !isPlainObject(override)) {
    return override as T;
  }
  const out: Record<string, unknown> = {};
  for (const key of Object.keys(base)) out[key] = cloneDeep(base[key]);
  for (const key of Object.keys(override)) {
    out[key] = mergeDeep(base[key], override[key]);
  }
  return out as T;
}

/**
 * Merges a user partial over {@link DEFAULT_CONFIG} into a complete config.
 *
 * @param partial - Any subset of the consolidated schema.
 */
export function resolveConfig(partial?: DeepPartial<ChartConfig>): ChartConfig {
  return mergeDeep(DEFAULT_CONFIG, partial ?? {});
}

